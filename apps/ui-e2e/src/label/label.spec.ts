import { expect, gotoStory, test } from '../support';

test.describe('label', () => {
	test.describe('default', () => {
		test.beforeEach(async ({ page }) => {
			await gotoStory(page, 'label--default');
		});

		test('should have an id autogenerated if none provided', async ({ page }) => {
			const label = page.locator('[hlmLabel]');
			await expect(label).not.toHaveCount(0);
			await expect(label.first()).toHaveAttribute('id', 'brn-label-1');
		});
	});
});

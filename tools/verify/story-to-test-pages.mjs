#!/usr/bin/env node
// Turns Storybook stories into test pages inside the docs app.
//
//   node tools/verify/story-to-test-pages.mjs dialog popover
//   node tools/verify/story-to-test-pages.mjs --all
//   node tools/verify/story-to-test-pages.mjs --all --check     (exit 1 if anything would change)
//
// Each story `export const NearViewportEdge` in a file titled `Popover` becomes the page
// `/test/popover/near-viewport-edge`, the same id Storybook gave it (`popover--near-viewport-edge`).
// A story the tool does not fully understand is never guessed at: it is left out and listed,
// with the reason, in apps/ui-e2e/story-report.json.

import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { pageClassName, storyId, titleId } from './lib/story-ids.mjs';
import { exportedHelperText, identifiersIn, parseStoryFile } from './lib/story-parse.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const STORIES_DIR = 'apps/ui-storybook/stories';
const PAGES_DIR = 'apps/app/src/app/pages/(test)/test';
const SHARED_FROM_PAGE = '../../../../shared/test';
const REPORT = 'apps/ui-e2e/story-report.json';
const MANIFEST = 'apps/ui-e2e/test-pages.json';
/**
 * Stories that should not become test pages, with the reason: `{ "select": { "WithHintAndError": "..." } }`.
 * For stories that are broken as written and that no test uses. Fixing the story is always better.
 */
const SKIP_LIST = 'apps/ui-e2e/story-skip.json';
const SELF = 'tools/verify/story-to-test-pages.mjs';
const MARKER = `// @generated by ${SELF}`;

/** Builds the files for one story file. Pure: reads nothing, writes nothing. */
export function buildTestPages(sourcePath, sourceText, skipList = {}) {
	const parsed = parseStoryFile(sourcePath, sourceText);
	const skipped = [];
	/** @type {{ file: string, content: string }[]} */
	const files = [];
	const pages = [];

	const relativeImport = parsed.importStatements?.find((statement) => statement.moduleSpecifier.text.startsWith('.'));
	if (relativeImport) {
		parsed.fileReasons.push(`relative import \`${relativeImport.moduleSpecifier.text}\` is not supported`);
	}
	if (parsed.fileReasons.length > 0 || !parsed.title) {
		return { title: parsed.title, files, pages, skipped, fileReasons: parsed.fileReasons };
	}

	const title = titleId(parsed.title);
	const directory = `${PAGES_DIR}/${title}`;
	const originalImports = parsed.importStatements.map((statement) => statement.getText(parsed.source)).join('\n');
	const casesModule = `./${title}.cases`;

	if (parsed.helpers.length > 0) {
		const body = parsed.helpers.map((statement) => exportedHelperText(statement, parsed.source)).join('\n\n');
		files.push({
			file: `${directory}/${title}.cases.ts`,
			content: [
				`${MARKER} from ${sourcePath}`,
				'// Do not edit. Change the story file and re-run the tool.',
				'// Components and helpers the test pages in this folder share.',
				originalImports,
				'',
				body,
				'',
			].join('\n'),
		});
	}

	for (const story of parsed.stories) {
		const listed = skipList[story.exportName];
		if (listed) story.reasons.push(`listed in ${SKIP_LIST}: ${listed}`);
		if (story.reasons.length > 0) {
			skipped.push({ story: story.exportName, reasons: [...new Set(story.reasons)] });
			continue;
		}
		const id = storyId(story.exportName);
		const className = pageClassName(parsed.title, story.exportName);
		const propKeys = new Set(story.props.map((field) => field.key));
		const args = story.args.filter((field) => !propKeys.has(field.key));

		const code = [
			...story.imports,
			...story.providers,
			...story.routeProviders,
			...story.props.map((f) => f.value),
			...story.setup.map((statement) => `(() => { ${statement} })`),
		];
		const used = identifiersIn([...code, ...args.map((field) => field.value)].join(',\n'));
		const fromCases = [...used].filter((name) => parsed.helperNames.has(name)).sort();

		const argKeys = args.map((field) => `'${field.key}'`).join(', ');
		let fields;
		let constructor;
		if (story.inConstructor) {
			// The story builds its props from local values or from the args, so the page does the same
			// in its constructor: the story's own statements first, then one assignment per prop.
			const body = [...story.setup, ...story.props.map((field) => field.value)].join('\n');
			const used = identifiersIn(`(() => { ${body} })`);
			const needsArgs = story.argsName && used.has(story.argsName);
			const named = story.namedArgs.filter((name) => used.has(name));
			fields = [
				...args.map((field) => `\tprotected ${field.key}: any = ${field.value};`),
				...story.props.map((field) => `\tprotected ${field.key}: any;`),
			];
			constructor = [
				'',
				'\tconstructor() {',
				...(args.length > 0 ? [`\t\tapplyTestArgs(this, [${argKeys}]);`] : []),
				...(needsArgs ? [`\t\tconst ${story.argsName} = this as any;`] : []),
				...(named.length > 0 ? [`\t\tconst { ${named.join(', ')} } = this as any;`] : []),
				...story.setup.map((statement) => `\t\t${statement}`),
				...story.props.map((field) => `\t\tthis.${field.key} = ${field.value};`),
				'\t}',
			];
		} else {
			fields = [
				...args.map((field) => `\tprotected ${field.key}: any = ${field.value};`),
				// Typed loosely like the args: Storybook never checked a story's props against the inputs
				// they are bound to (`activationMode: 'automatic'` would be a plain string here).
				...story.props.map((field) => `\tprotected ${field.key}: any = ${field.value};`),
			];
			constructor = args.length > 0 ? ['', '\tconstructor() {', `\t\tapplyTestArgs(this, [${argKeys}]);`, '\t}'] : [];
		}

		const routeMeta = [
			`\ttitle: 'Test: ${title} / ${id}',`,
			`\tmeta: [{ name: 'robots', content: 'noindex' }],`,
			...(story.routeProviders.length > 0 ? [`\tproviders: [${story.routeProviders.join(', ')}],`] : []),
		];

		const content = [
			`${MARKER} from ${sourcePath} (story ${story.exportName})`,
			'// Do not edit. Change the story and re-run the tool.',
			`import type { RouteMeta } from '@analogjs/router';`,
			`import { Component } from '@angular/core';`,
			...(args.length > 0 ? [`import { applyTestArgs } from '${SHARED_FROM_PAGE}/test-args';`] : []),
			`import { SpartanTestShell } from '${SHARED_FROM_PAGE}/test-shell';`,
			originalImports,
			...(fromCases.length > 0 ? [`import { ${fromCases.join(', ')} } from '${casesModule}';`] : []),
			'',
			'export const routeMeta: RouteMeta = {',
			...routeMeta,
			'};',
			'',
			'@Component({',
			`\tselector: 'spartan-test-${title}-${id}',`,
			`\timports: [${['SpartanTestShell', ...story.imports].join(', ')}],`,
			...(story.providers.length > 0 ? [`\tproviders: [${story.providers.join(', ')}],`] : []),
			`\ttemplate: \`<spartan-test-shell>${escapeTemplate(story.template)}</spartan-test-shell>\`,`,
			'})',
			`export default class ${className} {`,
			...fields,
			...constructor,
			'}',
			'',
		].join('\n');

		files.push({ file: `${directory}/${id}.page.ts`, content });
		pages.push({
			id: `${title}--${id}`,
			route: `/test/${title}/${id}`,
			source: sourcePath,
			story: story.exportName,
			args: args.map((field) => field.key),
			...(story.routeProviders.length > 0 ? { note: 'applicationConfig providers were placed on the route' } : {}),
		});
	}

	return { title, files, pages, skipped, fileReasons: [] };
}

function escapeTemplate(template) {
	return template.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

function buildIndexPage(pages) {
	const groups = new Map();
	for (const page of pages) {
		const [title] = page.id.split('--');
		if (!groups.has(title)) groups.set(title, []);
		groups.get(title).push(page);
	}
	const sections = [...groups.entries()]
		.map(
			([title, items]) => `
			<section class="space-y-2">
				<h2 class="text-lg font-semibold">${title}</h2>
				<ul class="list-disc space-y-1 pl-6">
					${items.map((page) => `<li><a class="underline" href="${page.route}">${page.id}</a></li>`).join('\n')}
				</ul>
			</section>`,
		)
		.join('\n');

	return [
		`${MARKER} from ${MANIFEST}`,
		'// Do not edit. Re-run the tool.',
		`import type { RouteMeta } from '@analogjs/router';`,
		`import { Component } from '@angular/core';`,
		`import { SpartanTestShell } from '../../../shared/test/test-shell';`,
		'',
		'export const routeMeta: RouteMeta = {',
		`\ttitle: 'Test pages',`,
		`\tmeta: [{ name: 'robots', content: 'noindex' }],`,
		'};',
		'',
		'@Component({',
		`\tselector: 'spartan-test-index',`,
		'\timports: [SpartanTestShell],',
		`\ttemplate: \`<spartan-test-shell><main class="space-y-6"><h1 class="text-2xl font-bold">Test pages</h1>`,
		`<p class="text-muted-foreground text-sm">Generated from the Storybook stories. The Playwright suite in apps/ui-e2e runs against these pages.</p>`,
		`${sections}</main></spartan-test-shell>\`,`,
		'})',
		'export default class TestIndexPage {}',
		'',
	].join('\n');
}

async function format(file, content) {
	const absolute = path.join(ROOT, file);
	const config = (await prettier.resolveConfig(absolute)) ?? {};
	return prettier.format(content, { ...config, filepath: absolute });
}

function readJson(file, fallback) {
	const absolute = path.join(ROOT, file);
	return existsSync(absolute) ? JSON.parse(readFileSync(absolute, 'utf8')) : fallback;
}

function sortKeys(object) {
	return Object.fromEntries(Object.entries(object).sort(([a], [b]) => a.localeCompare(b)));
}

function listStoryFiles() {
	const found = [];
	const walk = (directory) => {
		for (const entry of readdirSync(path.join(ROOT, directory), { withFileTypes: true })) {
			const relative = `${directory}/${entry.name}`;
			if (entry.isDirectory()) walk(relative);
			else if (entry.name.endsWith('.stories.ts')) found.push(relative);
		}
	};
	walk(STORIES_DIR);
	return found.sort();
}

async function main() {
	const argv = process.argv.slice(2);
	const check = argv.includes('--check');
	const all = argv.includes('--all');
	const names = argv.filter((argument) => !argument.startsWith('--'));
	if (!all && names.length === 0) {
		console.error(`Usage: node ${SELF} <story name> [...] | --all [--check]`);
		process.exit(2);
	}

	const available = listStoryFiles();
	const selected = all
		? available
		: names.map((name) => available.find((f) => path.basename(f, '.stories.ts') === name));
	const missing = names.filter((_, index) => !selected[index]);
	if (missing.length > 0) {
		console.error(`No story file for: ${missing.join(', ')}`);
		process.exit(2);
	}

	const report = readJson(REPORT, { generatedBy: SELF, files: {} });
	const manifest = readJson(MANIFEST, { generatedBy: SELF, pages: [] });
	const skipLists = readJson(SKIP_LIST, {});
	const writes = new Map();
	const removals = [];

	for (const sourcePath of selected) {
		const name = path.basename(sourcePath, '.stories.ts');
		const built = buildTestPages(sourcePath, readFileSync(path.join(ROOT, sourcePath), 'utf8'), skipLists[name] ?? {});
		for (const { file, content } of built.files) writes.set(file, await format(file, content));

		// Pages this tool wrote earlier for stories that no longer exist (or no longer convert).
		if (built.title) {
			const directory = `${PAGES_DIR}/${built.title}`;
			const absolute = path.join(ROOT, directory);
			for (const entry of existsSync(absolute) ? readdirSync(absolute) : []) {
				const file = `${directory}/${entry}`;
				if (writes.has(file)) continue;
				if (readFileSync(path.join(ROOT, file), 'utf8').startsWith(MARKER)) removals.push(file);
			}
		}

		report.files[name] = {
			source: sourcePath,
			title: built.title ?? null,
			pages: built.pages.map((page) => page.id),
			skipped: built.skipped,
			...(built.fileReasons.length > 0 ? { fileSkipped: built.fileReasons } : {}),
		};
		manifest.pages = [...manifest.pages.filter((page) => page.source !== sourcePath), ...built.pages];

		const skippedCount = built.fileReasons.length > 0 ? 'whole file' : built.skipped.length;
		console.log(`${name}: ${built.pages.length} pages, ${skippedCount} skipped`);
	}

	report.files = sortKeys(report.files);
	const entries = Object.values(report.files);
	report.totals = {
		files: entries.length,
		pages: entries.reduce((sum, entry) => sum + entry.pages.length, 0),
		skippedStories: entries.reduce((sum, entry) => sum + entry.skipped.length, 0),
		skippedFiles: entries.filter((entry) => entry.fileSkipped).length,
	};
	manifest.pages.sort((a, b) => a.id.localeCompare(b.id));

	const indexFile = `${PAGES_DIR}/index.page.ts`;
	writes.set(indexFile, await format(indexFile, buildIndexPage(manifest.pages)));
	writes.set(REPORT, await format(REPORT, JSON.stringify(report)));
	writes.set(MANIFEST, await format(MANIFEST, JSON.stringify(manifest)));

	const changed = [...writes].filter(([file, content]) => {
		const absolute = path.join(ROOT, file);
		return !existsSync(absolute) || readFileSync(absolute, 'utf8') !== content;
	});

	if (check) {
		for (const [file] of changed) console.error(`out of date: ${file}`);
		for (const file of removals) console.error(`stale: ${file}`);
		process.exit(changed.length + removals.length > 0 ? 1 : 0);
	}

	for (const [file, content] of changed) {
		mkdirSync(path.dirname(path.join(ROOT, file)), { recursive: true });
		writeFileSync(path.join(ROOT, file), content);
	}
	for (const file of removals) rmSync(path.join(ROOT, file));
	console.log(
		`${report.totals.pages} pages from ${report.totals.files} story files, ` +
			`${report.totals.skippedStories} stories and ${report.totals.skippedFiles} files skipped. ` +
			`${changed.length} files written, ${removals.length} removed.`,
	);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await main();
}

import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { format } from '../../lib/cy/format.mjs';
import { transformSource } from '../../lib/cy/transform.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '../../../..');

/** @param {string} src @param {Set<string>} [manualTitles] */
const t = (src, manualTitles) => transformSource(src, { sourcePath: 'x.cy.ts', basename: 'x', manualTitles });

describe('structure', () => {
	it('fixture converts to the expected formatted output', async () => {
		const src = readFileSync(path.join(here, 'fixtures/basic.cy.ts.txt'), 'utf8');
		const expected = readFileSync(path.join(here, 'fixtures/basic.expected.spec.ts.txt'), 'utf8');
		const r = transformSource(src, { sourcePath: 'fixtures/basic.cy.ts', basename: 'basic' });
		const f = await format(r.code, repoRoot, 'apps/ui-e2e/src/fixtures/basic.spec.ts');
		assert.ok(f.formatted, f.error);
		assert.equal(f.code, expected);
	});

	it('describe/it/hooks map to test.describe/test/test.beforeEach/test.afterEach', () => {
		const r = t(`describe('a', () => {
	beforeEach(() => { cy.visit('/iframe.html?id=a--b'); });
	afterEach(() => { cy.realPress('Escape'); });
	it('x', () => { cy.get('a').click(); });
});`);
		assert.match(r.code, /test\.describe\('a', \(\) => \{/);
		assert.match(r.code, /test\.beforeEach\(async \(\{ page \}\) => \{\n\t\tawait gotoStory\(page, 'a--b'\);/);
		assert.match(r.code, /test\.afterEach\(async \(\{ page \}\) => \{\n\t\tawait page\.keyboard\.press\('Escape'\);/);
		assert.match(r.code, /test\('x', async \(\{ page \}\) => \{/);
	});

	it('skip and only modifiers', () => {
		const r =
			t(`describe.skip('a', () => { it.skip('s', () => { cy.get('a'); }); it.only('o', () => { cy.get('a'); }); });
describe.only('b', () => { it('c', () => { cy.get('a'); }); });`);
		assert.match(r.code, /test\.describe\.skip\('a'/);
		assert.match(r.code, /test\.skip\('s'/);
		assert.match(r.code, /test\('o'/);
		assert.match(r.code, /test\.describe\('b'/);
		assert.ok(!r.code.includes('only'));
	});

	it('a beforeEach that becomes empty is not emitted', () => {
		const r = t(
			`describe('a', () => { beforeEach(() => { cy.injectAxe(); }); it('x', () => { cy.get('a').click(); }); });`,
		);
		assert.ok(!r.code.includes('beforeEach'));
	});

	it('only the support names actually used are imported', () => {
		const r = t(`describe('a', () => { it('x', () => { cy.get('a').click(); }); });`);
		assert.match(r.code, /^import \{ test \} from '\.\.\/support';$/m);
		const r2 = t(`describe('a', () => { it('x', () => { cy.get('#storybook-root').should('exist'); }); });`);
		assert.match(r2.code, /^import \{ STORY_ROOT, expect, test \} from '\.\.\/support';$/m);
	});

	it('header names the source and the manual file', () => {
		const r = t(`describe('a', () => {});`);
		assert.ok(r.code.startsWith('// @generated by tools/verify/cypress-to-playwright.mjs from x.cy.ts\n'));
		assert.ok(r.code.includes('Port skipped tests by hand in x.manual.spec.ts'));
	});

	it('titles built from string concatenation and templates are static', () => {
		const r = t("describe('a', () => { it(`multi\nline` + ' more', () => { cy.get('a'); }); });");
		assert.equal(r.tests[0].title, 'multi\nline more');
		assert.ok(r.code.includes("test('multi\\nline more'"));
	});

	it('comments between describe-level statements are kept; prettier-ignore is dropped', () => {
		const r = t(`describe('a', () => {
	// about the test
	// prettier-ignore
	it('x', () => { cy.get('a'); });
	// trailing note
});`);
		assert.ok(r.code.includes('// about the test'));
		assert.ok(r.code.includes('// trailing note'));
		assert.ok(!r.code.includes('prettier-ignore'));
	});
});

describe('helpers and scope-wide skips', () => {
	it('a test that calls a file-level helper is skipped and the helper is not emitted', () => {
		const r = t(`const open = () => cy.get('a').click();
describe('a', () => { it('x', () => { open(); }); it('y', () => { cy.get('a').click(); }); });`);
		assert.deepEqual(r.tests[0].reasons, ['uses helper open']);
		assert.equal(r.tests[1].status, 'converted');
		assert.ok(!r.code.includes('const open'));
	});

	it('a test that reads a describe-level const is skipped', () => {
		const r = t(`describe('a', () => { const label = /x/; it('x', () => { cy.findByText(label).click(); }); });`);
		assert.ok(r.tests[0].reasons.includes('uses helper label'));
	});

	it('an expression-bodied test calling a helper is skipped', () => {
		const r = t(`describe('a', () => { const run = (id) => cy.get(id); it('x', () => run('#a')); });`);
		assert.deepEqual(r.tests[0].reasons, ['uses helper run']);
		assert.ok(r.code.includes("run('#a')"));
	});

	it('an unsupported beforeEach skips every test in the describe and nested describes', () => {
		const r = t(`describe('a', () => {
	beforeEach(() => { cy.visit('/iframe.html?id=a--b'); cy.get('#t').then(() => {}); });
	it('x', () => { cy.get('a').click(); });
	describe('n', () => { it('y', () => { cy.get('a').click(); }); });
});
describe('b', () => { it('z', () => { cy.get('a').click(); }); });`);
		const [x, y, z] = r.tests;
		assert.deepEqual(x.reasons, ['unsupported beforeEach: unsupported command .then']);
		assert.deepEqual(y.reasons, ['unsupported beforeEach: unsupported command .then']);
		assert.deepEqual(y.describePath, ['a', 'n']);
		assert.equal(z.status, 'converted');
		assert.ok(!r.code.includes("gotoStory(page, 'a--b')"), 'the unsupported beforeEach is not emitted');
	});

	it('a beforeEach that uses a helper is unsupported', () => {
		const r = t(
			`describe('a', () => { const settle = () => cy.get('a'); beforeEach(() => { settle(); }); it('x', () => { cy.get('a'); }); });`,
		);
		assert.deepEqual(r.tests[0].reasons, ['unsupported beforeEach: uses helper settle']);
	});

	it('before/after hooks skip the scope', () => {
		const r = t(
			`describe('a', () => { before(() => { cy.visit('/iframe.html?id=a--b'); }); it('x', () => { cy.get('a'); }); });`,
		);
		assert.deepEqual(r.tests[0].reasons, ['unsupported before hook']);
	});

	it('tests generated in a loop are reported, not dropped', () => {
		const r = t(
			"describe('a', () => { const s = ['p', 'q']; s.forEach((v) => { it(`t ${v}`, () => { cy.visit(`/iframe.html?id=${v}`); }); }); });",
		);
		assert.equal(r.tests.length, 1);
		assert.equal(r.tests[0].status, 'skipped');
		assert.ok(r.tests[0].reasons.includes('test defined inside unsupported statement (s.forEach)'));
		assert.ok(r.tests[0].reasons.includes('non-literal test title'));
	});

	it('describe-level side effects skip the scope', () => {
		const r = t(
			`describe('a', () => { Cypress.on('uncaught:exception', () => false); it('x', () => { cy.get('a'); }); });`,
		);
		assert.deepEqual(r.tests[0].reasons, ['unsupported describe-level statement (Cypress.on)']);
	});
});

describe('manual ports', () => {
	const src = `describe('a', () => { it('needs work', () => { cy.get('a').then(() => {}); }); it('fine', () => { cy.get('a').click(); }); });`;

	it('a skipped test with a manual port of the same title is not emitted and is recorded as ported', () => {
		const r = t(src, new Set(['needs work']));
		assert.equal(r.tests[0].status, 'ported');
		assert.ok(!r.code.includes('needs work'));
		assert.ok(!r.code.includes('fixme'));
	});

	it('without a matching manual port the fixme is emitted', () => {
		const r = t(src, new Set(['other title']));
		assert.equal(r.tests[0].status, 'skipped');
		assert.ok(r.code.includes("test.fixme('needs work'"));
	});

	it('a manual port also takes the place of a test the tool could convert', () => {
		const r = t(src, new Set(['fine']));
		assert.equal(r.tests[1].status, 'ported');
	});
});

describe('determinism', () => {
	it('the same input gives byte-identical formatted output', async () => {
		const file = path.join(repoRoot, 'apps/ui-storybook-e2e/src/integration/dialog/dialog.cy.ts');
		const src = readFileSync(file, 'utf8');
		const outs = [];
		for (let i = 0; i < 2; i++) {
			const r = transformSource(src, { sourcePath: 'dialog.cy.ts', basename: 'dialog' });
			outs.push((await format(r.code, repoRoot, 'apps/ui-e2e/src/dialog/dialog.spec.ts')).code);
		}
		assert.equal(outs[0], outs[1]);
	});
});

describe('groups with nothing left to run', () => {
	it('leaves out a describe whose tests were all ported by hand, hooks included', () => {
		const src = `describe('ported', () => {
	beforeEach(() => {
		cy.visit('/iframe.html?id=a--b');
	});
	it('one', () => {
		cy.get('#x').then(($el) => $el.click());
	});
});
describe('kept', () => {
	it('two', () => {
		cy.get('#y').click();
	});
});`;
		const r = transformSource(src, { sourcePath: 'x.cy.ts', basename: 'x', manualTitles: new Set(['one']) });
		assert.doesNotMatch(r.code, /ported/);
		assert.doesNotMatch(r.code, /beforeEach/);
		assert.match(r.code, /test\.describe\('kept'/);
	});
});

describe('duplicate titles', () => {
	it('numbers the later ones, because Playwright refuses two tests with one title', () => {
		const src = `describe('g', () => {
	it('same', () => {
		cy.get('#a').click();
	});
	it('same', () => {
		cy.get('#b').click();
	});
	it('same', () => {
		cy.get('#c').then(() => {});
	});
});`;
		const r = transformSource(src, { sourcePath: 'x.cy.ts', basename: 'x' });
		assert.match(r.code, /test\('same', /);
		assert.match(r.code, /test\('same \(2\)', /);
		assert.match(r.code, /test\.fixme\('same \(3\)', /);
	});
});

describe('assertions on a subject that can hold several elements', () => {
	const body = (line) => t(`describe('g', () => { it('x', () => { ${line} }); });`).code;

	it('reads attributes from the first element, as jQuery does', () => {
		assert.match(
			body(`cy.findAllByRole('none').should('not.have.attr', 'aria-orientation', 'vertical');`),
			/expect\(page\.getByRole\('none'\)\.first\(\)\)\.not\.toHaveAttribute\('aria-orientation', 'vertical'\)/,
		);
		assert.match(
			body(`cy.get('.item').should('have.attr', 'data-x', '1');`),
			/page\.locator\('\.item'\)\.first\(\)\)\.toHaveAttribute/,
		);
	});

	it('treats focus as "any of them has focus"', () => {
		assert.match(
			body(`cy.findAllByText(/save/i).should('have.focus');`),
			/expect\(byText\(page, \/save\/i\)\.and\(page\.locator\(':focus'\)\)\)\.toHaveCount\(1\)/,
		);
		assert.match(
			body(`cy.findAllByText(/save/i).should('not.have.focus');`),
			/\.and\(page\.locator\(':focus'\)\)\)\.toHaveCount\(0\)/,
		);
	});

	it('leaves single-element subjects alone', () => {
		assert.match(
			body(`cy.findByText(/save/i).should('have.focus');`),
			/expect\(byText\(page, \/save\/i\)\)\.toBeFocused\(\)/,
		);
		assert.match(
			body(`cy.get('#one').should('have.attr', 'a', 'b');`),
			/expect\(page\.locator\('#one'\)\)\.toHaveAttribute/,
		);
		assert.match(
			body(`cy.get('.item').first().should('have.attr', 'a', 'b');`),
			/locator\('\.item'\)\.first\(\)\)\.toHaveAttribute/,
		);
		assert.match(
			body(`cy.findAllByRole('tab').should('have.length', 3);`),
			/expect\(page\.getByRole\('tab'\)\)\.toHaveCount\(3\)/,
		);
	});
});

describe('a manual port of a test the tool can convert', () => {
	it('replaces the generated test', () => {
		const src = `describe('g', () => {
	it('wrong as written', () => {
		cy.get('#a').click();
	});
	it('fine', () => {
		cy.get('#b').click();
	});
});`;
		const r = transformSource(src, {
			sourcePath: 'x.cy.ts',
			basename: 'x',
			manualTitles: new Set(['wrong as written']),
		});
		assert.doesNotMatch(r.code, /wrong as written/);
		assert.match(r.code, /test\('fine'/);
		assert.deepEqual(
			r.tests.map((test) => [test.title, test.status]),
			[
				['wrong as written', 'ported'],
				['fine', 'converted'],
			],
		);
	});
});

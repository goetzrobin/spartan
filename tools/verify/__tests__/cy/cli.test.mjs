import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { appendFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { after, before, describe, it } from 'node:test';
import { fileURLToPath } from 'node:url';
import { readManualTitles } from '../../lib/cy/manual.mjs';
import { mergeReport } from '../../lib/cy/report.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const cli = path.resolve(here, '../../cypress-to-playwright.mjs');

/** @type {string} */
let tmp;
/** @param {...string} args */
const runCli = (...args) => spawnSync(process.execPath, [cli, ...args], { encoding: 'utf8', cwd: os.tmpdir() });

before(() => {
	tmp = mkdtempSync(path.join(os.tmpdir(), 'cy2pw-'));
});
after(() => rmSync(tmp, { recursive: true, force: true }));

describe('cli', () => {
	it('writes specs and a report, and merges runs for different components', () => {
		const out = path.join(tmp, 'merge/src');
		const report = path.join(tmp, 'merge/report.json');
		let r = runCli('label', '--out-dir', out, '--report', report);
		assert.equal(r.status, 0, r.stderr);
		assert.match(r.stdout, /^label\/label: \d+ converted, \d+ skipped, \d+ ported -> /m);
		r = runCli('separator', '--out-dir', out, '--report', report);
		assert.equal(r.status, 0, r.stderr);
		const rep = JSON.parse(readFileSync(report, 'utf8'));
		assert.deepEqual(Object.keys(rep.files), ['label/label', 'separator/separator']);
		assert.equal(rep.generatedBy, 'tools/verify/cypress-to-playwright.mjs');
		assert.equal(rep.files['label/label'].source, 'apps/ui-storybook-e2e/src/integration/label/label.cy.ts');
		assert.equal(rep.totals.files, 2);
		assert.equal(rep.totals.tests, rep.totals.converted + rep.totals.skipped + rep.totals.ported);
		const spec = readFileSync(path.join(out, 'separator/separator.spec.ts'), 'utf8');
		assert.ok(spec.startsWith('// @generated by tools/verify/cypress-to-playwright.mjs from apps/ui-storybook-e2e/'));
	});

	it('writes one spec per .cy.ts file in a folder', () => {
		const out = path.join(tmp, 'multi/src');
		const r = runCli('tabs', '--out-dir', out, '--report', path.join(tmp, 'multi/r.json'));
		assert.equal(r.status, 0, r.stderr);
		for (const b of ['tabs--brnonly', 'tabs--default', 'tabs--default--manual', 'tabs--disabled', 'tabs--vertical'])
			assert.ok(readFileSync(path.join(out, 'tabs', `${b}.spec.ts`), 'utf8').length > 0, b);
	});

	it('is deterministic across runs and --check passes, then fails after an edit', () => {
		const out = path.join(tmp, 'check/src');
		const report = path.join(tmp, 'check/r.json');
		assert.equal(runCli('dialog', 'popover', '--out-dir', out, '--report', report).status, 0);
		const first = readFileSync(path.join(out, 'popover/popover.spec.ts'), 'utf8');
		const firstReport = readFileSync(report, 'utf8');
		assert.equal(runCli('popover', 'dialog', '--out-dir', out, '--report', report).status, 0);
		assert.equal(readFileSync(path.join(out, 'popover/popover.spec.ts'), 'utf8'), first);
		assert.equal(readFileSync(report, 'utf8'), firstReport);
		assert.equal(runCli('dialog', 'popover', '--check', '--out-dir', out, '--report', report).status, 0);
		appendFileSync(path.join(out, 'popover/popover.spec.ts'), '// edited\n');
		const r = runCli('dialog', 'popover', '--check', '--out-dir', out, '--report', report);
		assert.equal(r.status, 1);
		assert.match(r.stdout, /differs: .*popover\.spec\.ts/);
	});

	it('--dry-run prints and writes nothing', () => {
		const out = path.join(tmp, 'dry/src');
		const report = path.join(tmp, 'dry/r.json');
		const r = runCli('label', '--dry-run', '--out-dir', out, '--report', report);
		assert.equal(r.status, 0, r.stderr);
		assert.match(r.stdout, /\/\/ @generated by tools\/verify\/cypress-to-playwright\.mjs/);
		assert.throws(() => readFileSync(report));
	});

	it('records manual ports from <basename>.manual.spec.ts', () => {
		const out = path.join(tmp, 'manual/src');
		const report = path.join(tmp, 'manual/r.json');
		assert.equal(runCli('slider', '--out-dir', out, '--report', report).status, 0);
		const before = JSON.parse(readFileSync(report, 'utf8')).files['slider/slider'];
		assert.ok(before.skipped.length > 0, 'slider has skipped tests to port');
		const title = before.skipped[0].title;
		mkdirSync(path.join(out, 'slider'), { recursive: true });
		writeFileSync(
			path.join(out, 'slider/slider.manual.spec.ts'),
			`import { test } from '../support';\ntest.describe('x', () => {\n\ttest(${JSON.stringify(title)}, async () => {});\n});\n`,
		);
		assert.equal(runCli('slider', '--out-dir', out, '--report', report).status, 0);
		const afterEntry = JSON.parse(readFileSync(report, 'utf8')).files['slider/slider'];
		assert.deepEqual(afterEntry.ported, [title]);
		assert.equal(afterEntry.skipped.length, before.skipped.length - 1);
		assert.ok(
			!readFileSync(path.join(out, 'slider/slider.spec.ts'), 'utf8').includes(
				`test.fixme(${JSON.stringify(title).replace(/"/g, "'")}`,
			),
		);
	});

	it('rejects unknown components', () => {
		const r = runCli('no-such-component', '--dry-run');
		assert.equal(r.status, 2);
	});
});

describe('manual titles', () => {
	it('reads single, double and template-literal titles, ignoring templates with substitutions', () => {
		const f = path.join(tmp, 'm.manual.spec.ts');
		writeFileSync(
			f,
			"test('a', async () => {});\ntest(\"b\", async () => {});\ntest(`c`, async () => {});\ntest(`d ${x}`, async () => {});\ntest.fixme('e', async () => {});\n",
		);
		assert.deepEqual([...readManualTitles(f)].sort(), ['a', 'b', 'c', 'e']);
	});
});

describe('report merging', () => {
	const entry = (n) => ({
		source: `s${n}`,
		output: `o${n}`,
		converted: n,
		skipped: [{ title: 't', describePath: ['d'], reasons: ['r'] }],
		ported: ['p'],
	});

	it('keeps other components, replaces updated ones, sorts keys and recomputes totals', () => {
		const first = mergeReport(null, { 'b/b': entry(1), 'a/a': entry(2) });
		const merged = mergeReport(first, { 'c/c': entry(3), 'b/b': entry(5) });
		assert.deepEqual(Object.keys(merged.files), ['a/a', 'b/b', 'c/c']);
		assert.equal(merged.files['b/b'].converted, 5);
		assert.deepEqual(merged.totals, { files: 3, tests: 2 + 5 + 3 + 3 + 3, converted: 10, skipped: 3, ported: 3 });
	});

	it('is stable regardless of insertion order', () => {
		const a = mergeReport(null, { 'x/x': entry(1), 'y/y': entry(2) });
		const b = mergeReport(null, { 'y/y': entry(2), 'x/x': entry(1) });
		assert.equal(JSON.stringify(a), JSON.stringify(b));
	});
});
